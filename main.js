// src/calculators/rollingAverage.ts
function calculateRollingAverage(dailyBreakdown, todayStr) {
  const validDays = dailyBreakdown.filter((day) => {
    const isValidDate = day.date <= todayStr;
    const hasMacros = day.aggregate.calories > 0 || day.aggregate.protein > 0 || day.aggregate.fat > 0 || day.aggregate.carbs > 0 || day.aggregate.fibre > 0;
    return isValidDate && hasMacros;
  });
  const count = validDays.length;
  if (count === 0) return null;
  const sum = validDays.reduce((acc, day) => {
    acc.calories += day.aggregate.calories;
    acc.protein += day.aggregate.protein;
    acc.fat += day.aggregate.fat;
    acc.carbs += day.aggregate.carbs;
    acc.fibre += day.aggregate.fibre;
    return acc;
  }, { calories: 0, protein: 0, fat: 0, carbs: 0, fibre: 0 });
  const averages = {
    calories: sum.calories / count,
    protein: sum.protein / count,
    fat: sum.fat / count,
    carbs: sum.carbs / count,
    fibre: sum.fibre / count
  };
  return { count, averages };
}

// src/calculators/macroRatios.ts
function calculateMacroRatios(aggregate) {
  const totalCals = aggregate.calories || 1;
  const proteinPct = Math.round(aggregate.protein * 4 / totalCals * 100) || 0;
  const fatPct = Math.round(aggregate.fat * 9 / totalCals * 100) || 0;
  const carbsPct = Math.round(aggregate.carbs * 4 / totalCals * 100) || 0;
  const fibrePct = Math.round(aggregate.fibre * 2 / totalCals * 100) || 0;
  return {
    proteinPct,
    fatPct,
    carbsPct,
    fibrePct
  };
}

